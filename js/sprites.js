// Desenha um sprite escalado para caber em (w, h)
function drawSprite(ctx, rows, x, y, w, h, color) {
  const cols = rows[0].length;
  const px = w / cols, py = h / rows.length;
  ctx.fillStyle = color;
  for (let r = 0; r < rows.length; r++) {
    for (let c = 0; c < cols; c++) {
      if (rows[r][c] === '#') ctx.fillRect(Math.round(x + c * px), Math.round(y + r * py), Math.ceil(px), Math.ceil(py));
    }
  }
}
